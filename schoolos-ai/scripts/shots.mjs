import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = 'http://127.0.0.1:4173';
fs.mkdirSync('docs/screens', { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const as = async (c) => { await p.goto(BASE + '/demo', { waitUntil: 'networkidle' }); await p.getByRole('button', { name: new RegExp(c) }).click(); await p.waitForURL(/app/); await p.waitForLoadState('networkidle'); };
const shot = async (name, path, full = false) => { await p.goto(BASE + path, { waitUntil: 'networkidle' }); await p.waitForTimeout(900); await p.screenshot({ path: `docs/screens/${name}.png`, fullPage: full }); };
await shot('home', '/');
await as('Principal / Administrator');
await shot('admin-dashboard', '/app/admin', true);
await shot('admin-insights', '/app/admin/insights');
await as('Teacher');
await shot('teacher-attendance', '/app/teacher/attendance');
await shot('teacher-copilot', '/app/teacher/copilot');
await as('Student');
await shot('student-dashboard', '/app/student', true);
await shot('student-passport', '/app/student/passport', true);
await as('Parent');
await shot('parent-dashboard', '/app/parent', true);
await b.close();
