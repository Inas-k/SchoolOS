// Generates skooly-clone/src/color-parity.css from the original's measured CSSOM.
// The original's build resolves "colour at N% opacity" utilities to literal lab() values;
// Tailwind in this project leaves them as color-mix(), which computes to oklab(). Same colour,
// different serialization, so we restate those utility rules with the measured lab() values.
//
// NOTE: Tailwind flattens `@layer utilities` written in user CSS, so these rules end up
// unlayered and beat layered utilities. To keep hover/focus overrides working we also restate
// every measured colour `:hover` rule after the base rules (higher specificity, same layer).
import fs from 'node:fs';
const ROOT = 'c:/Users/inash/Downloads/Projects/Sckooly';
const all = JSON.parse(fs.readFileSync(`${ROOT}/clone-workspace/skooly/02-extraction/all-styles.json`, 'utf8'));
const rules = all.sheets.flatMap((s) => s.rules);

const SIMPLE = /^\.[A-Za-z0-9_\\\/\.\[\]\-%#:]+$/;
const COLOR_PROPS = /^(background-color|color|border-color|--tw-ring-color)\s*:/;
const onlyColor = (c) => c.split(';').map((x) => x.trim()).filter(Boolean).every((d) => COLOR_PROPS.test(d));

const base = [], hover = [];
const seen = new Set();
// Selectors whose measured rule resolves through color-mix() already serialize identically in
// Tailwind's output, so restating them would downgrade the match. Skip them entirely.
const mixed = new Set(rules.filter((r) => /color-mix/.test(r.c)).map((r) => r.s));
for (const r of rules) {
  if (mixed.has(r.s) && !/lab\(/.test(r.c.replace(/color-mix\([^)]*\)/g, ''))) continue;
  if (/color-mix/.test(r.c)) continue;
  if (!/^@layer utilities/.test(r.ctx)) continue;
  if (!SIMPLE.test(r.s)) continue;
  if (/min-width/.test(r.ctx)) continue;
  if (!onlyColor(r.c)) continue;
  const isHover = /hover: hover/.test(r.ctx) && /:hover$/.test(r.s);
  const hasLab = /lab\(/.test(r.c);
  if (!isHover && !hasLab) continue;
  const line = `${r.s}{${r.c}}`;
  if (seen.has(line)) continue;
  seen.add(line);
  (isHover ? hover : base).push(line);
}
// Shadow-colour utilities: the original mixes a literal lab() colour; Tailwind mixes the hex.
// Same colour, but the oklab() result differs in the 5th decimal. Restate with the measured lab().
const shadowColor = rules
  .filter((r) => /^@layer utilities/.test(r.ctx) && /^\.shadow-[a-z-]+\\\/\d+$/.test(r.s) && /lab\(/.test(r.c) && /color-mix/.test(r.c))
  .map((r) => `${r.s}{${r.c}}`);
const css = `/* GENERATED by tools/gen-color-parity.mjs from the original's measured CSSOM. Do not edit.
   Restates opacity-colour utilities with literal lab() values so computed colours serialize
   identically to the original, plus the matching :hover colour rules so hover still wins. */
@supports (color: lab(0% 0 0)) {
${base.join('\n')}
}
@media (hover: hover) {
${hover.join('\n')}
}
@supports (color: color-mix(in lab, red, red)) {
${shadowColor.join('\n')}
}
`;
fs.writeFileSync(`${ROOT}/skooly-clone/src/color-parity.css`, css);
console.log('base', base.length, 'hover', hover.length);
console.log(hover.join('\n'));
